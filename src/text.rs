use image::{Rgba, RgbaImage};

/// Simple bitmap font text renderer.
/// Renders text to an RGBA image with transparent background.
/// Uses a minimal built-in 8x16 font (no external dependencies).
pub struct TextRenderer {
    pub width: u32,
    pub height: u32,
}

impl TextRenderer {
    pub fn new(width: u32, height: u32) -> Self {
        Self { width, height }
    }

    /// Render now-playing text to an RGBA image.
    /// Returns the raw RGBA bytes.
    pub fn render_now_playing(&self, artist: &str, title: &str) -> Vec<u8> {
        let mut img = RgbaImage::new(self.width, self.height);

        // Background: fully transparent
        // (already zeroed)

        // Semi-transparent dark bar at bottom
        let bar_height = 48u32;
        let bar_y = self.height.saturating_sub(bar_height);
        for y in bar_y..self.height {
            for x in 0..self.width {
                img.put_pixel(x, y, Rgba([0, 0, 0, 140]));
            }
        }

        if artist.is_empty() && title.is_empty() {
            return img.into_raw();
        }

        // Render title (larger, brighter)
        let title_y = bar_y + 6;
        draw_text(&mut img, title, 12, title_y, Rgba([255, 255, 255, 230]), 2);

        // Render artist (smaller, dimmer)
        let artist_y = bar_y + 28;
        draw_text(&mut img, artist, 12, artist_y, Rgba([180, 180, 180, 200]), 1);

        img.into_raw()
    }
}

/// Draw text using a minimal built-in bitmap font.
/// Scale 1 = 5x7 pixels per char, scale 2 = 10x14.
fn draw_text(img: &mut RgbaImage, text: &str, x: u32, y: u32, color: Rgba<u8>, scale: u32) {
    let char_w = 6 * scale;
    let char_h = 8 * scale;
    let (img_w, img_h) = (img.width(), img.height());

    for (i, ch) in text.chars().enumerate() {
        let cx = x + i as u32 * char_w;
        if cx + char_w > img_w { break; }

        let glyph = get_glyph(ch);
        for row in 0..8u32 {
            let bits = glyph[row as usize];
            for col in 0..6u32 {
                if bits & (1 << (7 - col)) != 0 {
                    // Draw scaled pixel
                    for sy in 0..scale {
                        for sx in 0..scale {
                            let px = cx + col * scale + sx;
                            let py = y + row * scale + sy;
                            if py < img_h && px < img_w {
                                img.put_pixel(px, py, color);
                            }
                        }
                    }
                }
            }
        }
    }
}

/// Minimal 6x8 bitmap font (ASCII 32-126).
/// Each character is 8 bytes (8 rows of 8-bit wide data, only left 6 bits used).
fn get_glyph(ch: char) -> [u8; 8] {
    let idx = ch as u32;
    if idx < 32 || idx > 126 { return [0; 8]; }
    FONT[(idx - 32) as usize]
}

